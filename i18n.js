const LANGS = [["en", "English"], ["zh-Hans", "简体中文"], ["zh-Hant", "繁體中文"]];

// Saved choice, else the browser's language (Taiwan/Hong Kong/Macau -> Traditional)
const LANG = (() => {
  try { const s = localStorage.getItem("lang"); if (I18N[s]) return s; } catch {}
  const n = (navigator.language || "").toLowerCase();
  if (!n.startsWith("zh")) return "en";
  return /hant|tw|hk|mo/.test(n) ? "zh-Hant" : "zh-Hans";
})();
const LOCALE = { en: "en-CA", "zh-Hans": "zh-CN", "zh-Hant": "zh-TW" }[LANG];

function t(key, vars) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
  return s;
}
const tCat = c => t("cat." + c);

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

// A <select> that switches language; the page reloads so everything re-renders in it
function langPicker(select) {
  select.innerHTML = LANGS.map(([v, label]) => `<option value="${v}"${v === LANG ? " selected" : ""}>${label}</option>`).join("");
  select.setAttribute("aria-label", t("language"));
  select.onchange = () => {
    try { localStorage.setItem("lang", select.value); } catch {}
    location.reload();
  };
}
